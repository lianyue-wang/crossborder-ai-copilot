# 【学习目标】
# 1. 理解 messages 数组为什么要存历史对话
# 2. 理解三种角色：system / user / assistant
# 3. 写出一个能连续对话的脚本

# 【核心概念】
# 大模型本身没有记忆！你每次调API，它都是"失忆"的。
# 它怎么知道你们聊过什么？——你必须把历史对话每次都传给它。
#
# messages 就是一个"对话记录"列表，每次调用都传完整的：
# [
#   {"role": "system", "content": "你是谁"},
#   {"role": "user",   "content": "我第一句话"},
#   {"role": "assistant", "content": "AI第一句回复"},
#   {"role": "user",   "content": "我第二句话"},
# ]

# ========== 初始化（我帮你写好了）==========
from dotenv import load_dotenv
import os
from openai import OpenAI

load_dotenv()
client = OpenAI(
    api_key=os.getenv("DEEPSEEK_API_KEY"),
    base_url="https://api.deepseek.com"
)

messages = [
    {"role":"system","content":"您是一名跨境电商选品顾问"}
]

print("=== 选品顾问AI（输入'退出'结束）===\n")

# ========== 你来写 ==========
# 现在messages已经有了system角色。下面全部由你自己写。
#
# ===== 第1步：创建无限循环 =====
# 写一个 while True:
# 为什么：你不想每说一句话就重新运行脚本，要像微信聊天那样一直说一直回。
#
# ===== 第2步：获取用户输入 =====
# 在循环里面，用 input("你: ") 让用户打字，结果存到一个变量里。
# 为什么：程序需要知道用户说了什么才能发给AI。
#
# ===== 第3步：判断退出 =====
# 如果用户输入的是"退出"，就用 break 跳出循环。
# 为什么：用户需要一个办法结束聊天，不然程序永远跑下去。
#
# ===== 第4步：把用户消息存进messages（关键！）=====
# 用 messages.append(...) 加一条字典：
#   role 写 "user"
#   content 写用户刚才输入的内容
# 为什么：大模型没有记忆，每次都要把完整对话历史传给它。
#         不加这步，AI就不知道用户刚说了什么。
#
# ===== 第5步：调AI =====
# 用 client.chat.completions.create()，传两个参数：
#   model="deepseek-chat"
#   messages=messages（把你维护的整个对话记录传进去）
# 把返回结果存到一个变量里。
# 为什么：这是请求大模型回复的标准调用方式，和01一样，
#         只是这次传的messages更长（因为有历史记录）。
#
# ===== 第6步：取出回复内容 =====
# 从返回结果里取AI说的话：返回变量.choices[0].message.content
# 存到一个变量里。
# 为什么：API返回的是一个大对象，你要的回复文字藏在这个路径里。
#
# ===== 第7步：把AI回复也存进messages（关键！）=====
# 再用 messages.append(...) 加一条字典：
#   role 写 "assistant"
#   content 写刚才取出的AI回复
# 为什么：下一轮对话时，AI需要知道自己上一句说了什么，否则上下文就断了。
#
# ===== 第8步：打印回复 =====
# 把AI回复print出来，让用户看到。
# 为什么：用户需要看到AI说了什么。
#
# ===== 关键理解 =====
# 第4步和第7步是核心：
#   不加第4步：AI不知道你刚说了什么
#   不加第7步：AI不知道自己上一句说了什么
#   两个都不加：每次对话都是第一次见面


